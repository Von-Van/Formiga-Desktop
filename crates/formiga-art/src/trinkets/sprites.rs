/// The grid for one variant, if it is one of these.
pub(super) fn grid(variant: u8) -> Option<&'static [&'static str; 12]> {
    variant
        .checked_sub(FIRST)
        .and_then(|index| GRIDS.get(usize::from(index)))
}

/// Where the glint goes on a grid-drawn find: the first light or white pixel far enough inside
/// the cell for its rays to stay in it, reading the grid top to bottom, or its middle if it has
/// none.
pub(super) fn glint_spot(grid: &[&str; 12]) -> (i32, i32) {
    let mut first_opaque = None;
    for (row, line) in grid.iter().enumerate() {
        for (column, ch) in line.chars().enumerate() {
            let (x, y) = (column as i32 + 2, row as i32 + 2);
            if ch != '.' && first_opaque.is_none() && (4..=11).contains(&x) && y >= 4 {
                first_opaque = Some((x, y));
            }
            if matches!(ch, 'l' | 'w') && (4..=11).contains(&x) && (4..=11).contains(&y) {
                return (x, y);
            }
        }
    }
    first_opaque.unwrap_or((8, 8))
}
