//! The finds added in 0.60.0, drawn as small grids of characters rather than one function each.
//!
//! Each grid is the 12x12 interior of a 16x16 cell, placed two pixels in from its top-left corner
//! so the outline pass has room for its edge. The characters name the same five inks every
//! keepsake is drawn from — `b` body, `d` deep, `l` light, `a` accent, `k` the outline colour used
//! for a detail inside the shape — plus two fixed colours, `w` for white things (paper, petals,
//! shells, dice) and `c` for cream ones (wood, pastry, card). `.` is empty. Only the interior is
//! written: the outline is drawn round it afterwards, exactly as it is for the first sixteen.
//!
//! The top two rows keep to the middle four columns and the third row to the middle six, because
//! the corners of a held keepsake's cell land on its holder's eyes and are always cleared.

